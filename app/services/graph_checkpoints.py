"""LangGraph persistence in a dedicated PostgreSQL schema, separate from retired data."""

from collections.abc import Iterator
from contextlib import contextmanager

from langgraph.checkpoint.postgres import PostgresSaver
from psycopg import Connection
from psycopg import Error as PsycopgError
from psycopg.rows import dict_row
from sqlalchemy import text
from sqlalchemy.engine import make_url

from app.config import get_settings
from app.errors import storage_error


@contextmanager
def checkpoint_store() -> Iterator[PostgresSaver]:
    url = make_url(get_settings().database_url).set(drivername="postgresql")
    with Connection.connect(
        url.render_as_string(hide_password=False),
        autocommit=True,
        prepare_threshold=0,
        row_factory=dict_row,
        connect_timeout=get_settings().database_connect_timeout,
        options=f"-c search_path=xinyu_graph -c statement_timeout={get_settings().database_statement_timeout_ms}",
    ) as conn:
        try:
            yield PostgresSaver(conn)
        except PsycopgError as exc:
            failure = storage_error(exc)
            if failure:
                raise failure from None
            raise


def prepare_checkpoints():
    with checkpoint_store() as saver:
        saver.setup()
    from app.services.storage_budget import configure_storage

    configure_storage()


def clear_checkpoints(owner: str, db=None):
    # Thread IDs are generated by the server; every API caller is scoped by the owner dependency.
    prefix = "xinyu:" + owner + ":"
    if db is not None:
        for table in ("checkpoints", "checkpoint_blobs", "checkpoint_writes"):
            db.execute(
                text(f"DELETE FROM xinyu_graph.{table} WHERE thread_id LIKE :prefix"),
                {"prefix": prefix + "%"},
            )
        return
    # Same three tables as the installed PostgresSaver.delete_thread, batched by the server-owned prefix.
    # Include orphan blobs/writes even if a crash occurred before their checkpoints row was inserted.
    with (
        checkpoint_store() as saver,
        saver.conn.transaction(),
        saver.conn.cursor() as cursor,
    ):
        for table in ("checkpoints", "checkpoint_blobs", "checkpoint_writes"):
            cursor.execute(
                f"DELETE FROM {table} WHERE thread_id LIKE %s", (prefix + "%",)
            )


def delete_checkpoint_thread(thread_id, db=None):
    if db is not None:
        for table in ("checkpoints", "checkpoint_blobs", "checkpoint_writes"):
            db.execute(
                text(f"DELETE FROM xinyu_graph.{table} WHERE thread_id=:thread"),
                {"thread": thread_id},
            )
    else:
        with checkpoint_store() as saver:
            saver.delete_thread(thread_id)
